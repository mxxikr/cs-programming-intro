namespace Variable;

class MainClass
{
    static void Main(string[] args)
    {
        // 변수 선언과 초기화
        bool boolVariable = true;
        int intVariable = 10;
        float floatVariable = 3.4f;
        char charVariable = 'a';
        
        // 변수에 저장 된 값 콘솔에 출력
        Console.WriteLine(boolVariable);
        Console.WriteLine(intVariable);
        Console.WriteLine(floatVariable);
        Console.WriteLine(charVariable);
    }
}